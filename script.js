const languageButtons = document.querySelectorAll("[data-lang]");

function setLanguage(language) {
  const copy = translations[language];
  if (!copy) return;

  document.documentElement.lang = language;
  document.querySelectorAll("[data-i18n]").forEach((element) => {
    const key = element.dataset.i18n;
    if (copy[key]) element.textContent = copy[key];
  });
  document.querySelectorAll("[data-i18n-html]").forEach((element) => {
    const key = element.dataset.i18nHtml;
    if (copy[key]) element.innerHTML = copy[key];
  });

  languageButtons.forEach((button) => {
    const active = button.dataset.lang === language;
    button.classList.toggle("active", active);
    button.setAttribute("aria-pressed", String(active));
  });

  document.title = language === "pt"
    ? "Murphy's Law Irish Pub & Grill | Lagoa, São Miguel"
    : "Murphy's Law Irish Pub & Grill | Lagoa, São Miguel";

  try {
    localStorage.setItem("murphys-language", language);
  } catch (_) {
    // The site remains fully usable when browser storage is unavailable.
  }
}

languageButtons.forEach((button) => {
  button.addEventListener("click", () => setLanguage(button.dataset.lang));
});

let preferredLanguage = "en";
try {
  preferredLanguage = localStorage.getItem("murphys-language") || (navigator.language.startsWith("pt") ? "pt" : "en");
} catch (_) {
  preferredLanguage = navigator.language.startsWith("pt") ? "pt" : "en";
}
setLanguage(preferredLanguage);

const revealElements = document.querySelectorAll(".reveal");
if ("IntersectionObserver" in window) {
  const observer = new IntersectionObserver(
    (entries) => {
      entries.forEach((entry) => {
        if (entry.isIntersecting) {
          entry.target.classList.add("visible");
          observer.unobserve(entry.target);
        }
      });
    },
    { threshold: 0.12 }
  );
  revealElements.forEach((element) => observer.observe(element));
} else {
  revealElements.forEach((element) => element.classList.add("visible"));
}
